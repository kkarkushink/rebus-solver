#ifndef PUZZLE_H
#define PUZZLE_H

#include <stddef.h>

/*
 * Решает числовой ребус вида "SEND + MORE = MONEY".
 *
 * Поддерживаются четыре арифметических действия (в одном ребусе используется
 * только одно из них, смешивать знаки в одном выражении нельзя):
 *   - сложение: от 2 до 7 слагаемых;
 *   - вычитание, умножение и деление: от 2 до 7 операндов.
 *
 * Цепочки вычитаний и делений вычисляются слева направо. При делении каждый
 * промежуточный результат должен быть целым, а делитель не может быть равен 0.
 * Примеры: "SEND + MORE = MONEY", "ABC - D - E = FG",
 *          "A * B * C = DE", "ABC / D / E = F".
 *
 * puzzle       - входная строка ребуса (слова из заглавных латинских букв,
 *                разделённые знаком действия и завершающиеся "= СЛОВО");
 * result       - буфер, в который записывается строка решения,
 *                например "9567 + 1085 = 10652";
 * result_size  - размер буфера result.
 *
 * Возвращает 1, если решение найдено и записано в result, иначе 0.
 */
int solve_puzzle(const char *puzzle, char *result, size_t result_size);

#endif /* PUZZLE_H */
